class NetworkSimulator:
    """
    Thread-based network telemetry simulation engine.
    Generates realistic baseline and attack traffic patterns.
    All data is clearly labeled as SIMULATION.
    """

    def __init__(self):
        self._lock = threading.Lock()
        self._thread: Optional[threading.Thread] = None
        self._running = False
        self._current_attack: Optional[str] = None
        self._attack_target: Optional[str] = None
        self._attack_source: Optional[str] = None
        self._attack_cycles_remaining = 0
        self._cycle_count = 0
        self._last_telemetry: Dict[str, Any] = {}
        self._alerts_generated = 0
        self._incidents_created = 0
        self.TELEMETRY_INTERVAL_SEC = 5

    @property
    def is_running(self) -> bool:
        with self._lock:
            return self._running

    @property
    def current_attack(self) -> Optional[str]:
        with self._lock:
            return self._current_attack

    def start(self):
        with self._lock:
            if self._running:
                return
            self._running = True
            self._thread = threading.Thread(target=self._run_loop, daemon=True)
            self._thread.start()
            logger.info("[SIMULATOR] Network simulation engine started.")

    def stop(self):
        with self._lock:
            self._running = False
            self._current_attack = None
        if self._thread:
            self._thread.join(timeout=10)
            logger.info("[SIMULATOR] Network simulation engine stopped.")

    def trigger_attack(self, attack_type: str, target_ip: Optional[str] = None, source_ip: Optional[str] = None, duration_cycles: int = 3):
        """Trigger a specific attack scenario. Duration is in simulation cycles (each ~5s)."""
        if attack_type not in ATTACK_SIGNATURES:
            raise ValueError(f"Unknown attack type: {attack_type}. Valid: {list(ATTACK_SIGNATURES.keys())}")

        chosen_target = target_ip
        if not chosen_target:
            preferred = ATTACK_PREFERRED_TARGETS.get(attack_type, list(ASSET_IPS.keys()))
            chosen_target = random.choice(preferred)

        chosen_source = source_ip or random.choice(ATTACKER_IPS)

        with self._lock:
            self._current_attack = attack_type
            self._attack_target = chosen_target
            self._attack_source = chosen_source
            self._attack_cycles_remaining = max(1, duration_cycles)

        logger.info(f"[SIMULATOR] Attack triggered: {attack_type} from {chosen_source} -> {chosen_target} for {duration_cycles} cycles")
        return {
            "attack_type": attack_type,
            "source_ip": chosen_source,
            "target_ip": chosen_target,
            "duration_cycles": duration_cycles,
            "note": "SIMULATION MODE - synthetic traffic"
        }

    def get_status(self) -> Dict[str, Any]:
        with self._lock:
            return {
                "running": self._running,
                "mode": "SIMULATION",
                "current_attack": self._current_attack,
                "attack_target": self._attack_target,
                "attack_source": self._attack_source,
                "attack_cycles_remaining": self._attack_cycles_remaining,
                "cycle_count": self._cycle_count,
                "alerts_generated": self._alerts_generated,
                "incidents_created": self._incidents_created,
                "last_telemetry": self._last_telemetry,
                "note": "All telemetry is simulated for academic demonstration purposes."
            }

    def _run_loop(self):
        while True:
            with self._lock:
                if not self._running:
                    break
                attack = self._current_attack
                target = self._attack_target
                source = self._attack_source
                remaining = self._attack_cycles_remaining

            try:
                if attack and remaining > 0:
                    telemetry = self._generate_attack_telemetry(attack)
                    self._write_telemetry(telemetry)
                    self._maybe_create_alert(attack, source, target, telemetry)
                    with self._lock:
                        self._attack_cycles_remaining -= 1
                        if self._attack_cycles_remaining <= 0:
                            self._current_attack = None
                            self._attack_target = None
                            self._attack_source = None
                            logger.info("[SIMULATOR] Attack scenario completed.")
                else:
                    # Auto-trigger random attack occasionally (every ~60s = 12 cycles at 5s interval)
                    if self._cycle_count > 0 and self._cycle_count % 12 == 0:
                        self._auto_trigger_random_attack()
                    else:
                        telemetry = self._generate_normal_telemetry()
                        self._write_telemetry(telemetry)

            except Exception as e:
                logger.error(f"[SIMULATOR] Error in simulation cycle: {e}")

            with self._lock:
                self._cycle_count += 1

            time.sleep(self.TELEMETRY_INTERVAL_SEC)

    def _auto_trigger_random_attack(self):
        """Randomly trigger an attack scenario for continuous demonstration."""
        attack_type = random.choice(list(ATTACK_SIGNATURES.keys()))
        preferred = ATTACK_PREFERRED_TARGETS.get(attack_type, list(ASSET_IPS.keys()))
        target = random.choice(preferred)
        source = random.choice(ATTACKER_IPS)

        with self._lock:
            self._current_attack = attack_type
            self._attack_target = target
            self._attack_source = source
            self._attack_cycles_remaining = random.randint(1, 3)

        logger.info(f"[SIMULATOR] Auto-triggered attack: {attack_type} -> {target}")

