    def _write_telemetry(self, telemetry: Dict[str, Any]):
        db = SessionLocal()
        try:
            sample = NetworkMetricSample(
                timestamp=datetime.utcnow(),
                switch_id="s1-simulation",
                host_ip=self._attack_target or "10.0.0.10",
                throughput_mbps=telemetry["throughput_mbps"],
                packet_loss_pct=telemetry["packet_loss_pct"],
                latency_ms=telemetry["latency_ms"],
                jitter_ms=telemetry["jitter_ms"],
                packets_per_sec=telemetry["packets_per_sec"],
                bytes_per_sec=telemetry["bytes_per_sec"],
                active_flows=telemetry["active_flows"],
                drop_count=telemetry["drop_count"],
            )
            db.add(sample)
            db.commit()
            with self._lock:
                self._last_telemetry = {**telemetry, "timestamp": datetime.utcnow().isoformat()}
        except Exception as e:
            logger.error(f"[SIMULATOR] Failed to write telemetry: {e}")
            db.rollback()
        finally:
            db.close()

    def _maybe_create_alert(self, attack_type: str, source_ip: str, target_ip: str, telemetry: Dict[str, Any]):
        """Create a SecurityAlert and Incident for the attack if not already active."""
        db = SessionLocal()
        try:
            # Check for existing open incident with same source+dest
            existing = db.query(Incident).filter(
                Incident.source_ip == source_ip,
                Incident.destination_ip == target_ip,
                Incident.status.in_(["NEW", "ASSESSING", "EVALUATING", "PENDING_APPROVAL", "READY_TO_EXECUTE"])
            ).first()

            if existing:
                # Don't create duplicate alerts for same active incident
                return

            # Create alert
            signature = random.choice(ATTACK_SIGNATURES[attack_type])
            severity = ATTACK_SEVERITY[attack_type]
            protocol = ATTACK_PROTOCOLS[attack_type]
            dest_port = ATTACK_DEST_PORTS[attack_type]

            alert = SecurityAlert(
                source="SIMULATION",
                alert_type=attack_type,
                severity=severity,
                source_ip=source_ip,
                destination_ip=target_ip,
                source_port=random.randint(1024, 65535),
                destination_port=dest_port,
                protocol=protocol,
                signature=f"[SIMULATION] {signature}",
                raw_payload={
                    "packets_per_second": telemetry["packets_per_sec"],
                    "bytes_per_second": telemetry["bytes_per_sec"],
                    "active_flows": telemetry["active_flows"],
                    "simulation": True
                }
            )
            db.add(alert)
            db.flush()

            # Create incident
            # ML-based confidence: higher for known attack types
            confidence_map = {
                "DOS_SYN_FLOOD": 0.88,
                "PORT_SCAN": 0.82,
                "BRUTE_FORCE": 0.85,
                "DNS_AMPLIFICATION_FLOOD": 0.90,
                "UNKNOWN_ANOMALY": 0.65,
            }
            confidence = confidence_map.get(attack_type, 0.70)
            # Add slight randomness
            confidence = round(min(0.99, max(0.50, confidence + random.uniform(-0.05, 0.05))), 4)

            incident = Incident(
                title=f"[SIM] {attack_type.replace('_', ' ').title()} from {source_ip}",
                threat_type=attack_type,
                severity=severity,
                status="NEW",
                source_ip=source_ip,
                destination_ip=target_ip,
                protocol=protocol,
                threat_confidence=confidence,
                uncertainty=round(random.uniform(0.12, 0.28), 4)
            )
            db.add(incident)
            db.flush()

            alert.incident_id = incident.id
            db.commit()

            with self._lock:
                self._alerts_generated += 1
                self._incidents_created += 1

            logger.info(f"[SIMULATOR] Alert+Incident created: {attack_type} #{incident.id} ({source_ip} -> {target_ip})")

        except Exception as e:
            logger.error(f"[SIMULATOR] Failed to create alert/incident: {e}")
            db.rollback()
        finally:
            db.close()


